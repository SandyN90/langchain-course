from dotenv import load_dotenv
from langchain.chat_models import init_chat_model

from langchain_core.tools import tool
from langchain_core.messages import HumanMessage, SystemMessage, ToolMessage
from langsmith import traceable
load_dotenv()

max_iterations = 10
model = "qwen3:1.7b"

#--------------------------------tools--------------------------------
@tool
def get_product_price(product_name: str) -> float:
    """Look up the price of a product in the catalog."""
    print(f">>Executing get_product_price tool for the price of {product_name}")
    prices={"laptop":1299.99, "headphones":149.99, "keyboard":89.50}
    return prices.get(product_name, 0.0)

@tool
def apply_discount(price: float, discount_tier: str) -> float:
    """Apply a discount tier to the price of a product and return final price.
    available tiers: bronze, silver, gold,"""

    print(f">>Executing apply_discount tool for the price of {price} with {discount_tier}% discount")
    discount_percentages={"bronze":5, "silver":12, "gold":13}
    discount = discount_percentages.get(discount_tier, 0)
    return round(price * (1 - discount / 100), 2)


#-----------Agent Loop--------------------------------


@traceable
def agent_loop(question: str):
    tools = [get_product_price, apply_discount]
    tools_dict = {tool.name: tool for tool in tools}
    llm = init_chat_model(f"ollama:{model}", temperature=0.0)
    llm_with_tools = llm.bind_tools(tools)

    print(f"Question: {question}")
    print("="*60)

    messages = [
        SystemMessage(
            content=(
                "You are a helpful shopping assistant. "
                "You have access to a product catalog tool "
                "and a discount tool.\n\n"
                "STRICT RULES — you must follow these exactly:\n"
                "1. NEVER guess or assume any product price. "
                "You MUST call get_product_price first to get the real price.\n"
                "2. Only call apply_discount AFTER you have received "
                "a price from get_product_price. Pass the exact price "
                "returned by get_product_price — do NOT pass a made-up number.\n"
                "3. NEVER calculate discounts yourself using math. "
                "Always use the apply_discount tool.\n"
                "4. If the user does not specify a discount tier, "
                "ask them which tier to use — do NOT assume one."
            )
        ),
        HumanMessage(content=question),
    ]

    pending_tool_calls = []
    for iteration in range(max_iterations + 1):
        print(f"---------------Iteration {iteration + 1}-----------------")
        # ai_message = llm_with_tools.invoke(messages)

        # tool_calls = ai_message.tool_calls
        if pending_tool_calls:
        # Execute a tool call already generated by the model.
            tool_call = pending_tool_calls.pop(0)
        else:
            ai_message = llm_with_tools.invoke(messages)

            # print("AI tool calls:", ai_message.tool_calls)

            if not ai_message.tool_calls:
                return ai_message.content

            # Preserve the original AI message containing ALL tool calls.
            messages.append(ai_message)

            pending_tool_calls.extend(ai_message.tool_calls)
            tool_call = pending_tool_calls.pop(0)
        
        # #if tool calls, execute the tool calls
        # for tool_call in tool_calls:
        #     print(f"\nFinal Answer: {ai_message.content}")
        #     return ai_message.content

        # process only the first tool call - force one tool per iteration
        # tool_call = tool_calls[0]
        tool_name = tool_call.get("name")
        tool_args = tool_call.get("args", {})
        tool_call_id = tool_call.get("id")

        print(f"   [Tool selected]  {tool_name} with args: {tool_args}")
        tool_to_use = tools_dict.get(tool_name)

        if tool_to_use is None:
            raise ValueError(f"Tool {tool_name} not found")
        observation = tool_to_use.invoke(tool_args)

        print(f"   [Tool result]  {observation}")
        messages.append(ai_message)
        messages.append(
            ToolMessage(content=str(observation), tool_call_id=tool_call_id)
        )
        #if no tool calls, this is the final answer
        if not pending_tool_calls:
            return ai_message.content
    print(f"Error: Max iterations reached. No final answer found.")
    return None

if __name__ == "__main__":
    print("Hello langchain Agent. (.bind_tools)!")
    # question = "What is the price of a laptop with a bronze discount?"
    result = agent_loop("What is price of laptop after gold discount?")
    print(result)